export function obterRegiaoPorId(regiaoId) {
  return (
    REGIOES_AREA_AFETADA.find((r) => r.id === regiaoId) ||
    REGIOES_AREA_AFETADA[0]
  )
}

export function inferirLocalizacaoNoticia(noticia = {}) {
  const texto = `${noticia.titulo || ''} ${noticia.descricao || ''}`.toLowerCase()

  for (const loc of LOCAIS_REFERENCIA) {
    if (loc.termos.some((termo) => texto.includes(termo))) {
      const regiao = obterRegiaoPorId(loc.regiaoId)
      return {
        ...loc,
        regiao,
        tipoMapa:
          noticia.categoria === 'queimadas' ? 'queimada' : 'desmatamento',
      }
    }
  }

  if (noticia.categoria === 'para') {
    const regiao = obterRegiaoPorId('sul_para_xingu')
    return {
      rotulo: 'Estado do Pará (PA)',
      municipio: 'Pará',
      estado: 'PA',
      latitude: -4.45,
      longitude: -52.48,
      precisao: 'Corredor de referência no Estado do Pará',
      regiaoId: 'sul_para_xingu',
      regiao,
      tipoMapa: 'desmatamento',
    }
  }

  const regiaoPadrao = obterRegiaoPorId(PADRAO_AMAZONIA.regiaoId)
  return {
    ...PADRAO_AMAZONIA,
    regiao: regiaoPadrao,
    tipoMapa: noticia.categoria === 'queimadas' ? 'queimada' : 'desmatamento',
  }
}

export function construirPoligonoAreaAfetadaNoticia(noticia = {}) {
  const loc = inferirLocalizacaoNoticia(noticia)
  const reg = loc.regiao || REGIOES_AREA_AFETADA[0]
  const ehFogo = noticia.categoria === 'queimadas'

  return {
    id: `poly-${noticia.id || reg.id}`,
    rotulo: `Área afetada: ${reg.nome}`,
    subtitulo: `Notícia: ${noticia.titulo || loc.rotulo}`,
    cor: ehFogo ? '#dc2626' : '#ea580c',
    preenchimento: ehFogo ? '#ef4444' : '#ef4444',
    opacidade: 0.44,
    coordenadas: reg.coordenadas,
    regiao: reg,
  }
}

export function construirPontoMapaNoticia(noticia = {}, indice = 0) {
  const loc = inferirLocalizacaoNoticia(noticia)
  const idNum = Number(noticia.id || indice || 1)
  const deltaLat = ((idNum % 7) - 3) * 0.08
  const deltaLon = (((idNum * 3) % 7) - 3) * 0.08

  return {
    id: noticia.id,
    codigo: noticia.veiculo || 'Notícia',
    tipo: loc.tipoMapa,
    municipio: loc.municipio || loc.rotulo,
    estado: loc.estado,
    latitude: Number((loc.latitude + deltaLat).toFixed(4)),
    longitude: Number((loc.longitude + deltaLon).toFixed(4)),
    rotuloLocal: loc.rotulo,
    precisaoLocal: loc.precisao,
    regiaoId: loc.regiaoId,
    noticia,
  }
}

export function cruzarImpactoComMonitoramento(noticia = {}, monitoramento = null) {
  const loc = inferirLocalizacaoNoticia(noticia)
  const poligonoArea = construirPoligonoAreaAfetadaNoticia(noticia)

  if (!monitoramento) {
    return {
      localizacao: loc,
      poligonoArea,
      ufResumo: null,
      focosMunicipio: [],
      pontosOficiaisProximos: [],
    }
  }

  const porEstado = Array.isArray(monitoramento.por_estado)
    ? monitoramento.por_estado
    : []
  const ufResumo =
    porEstado.find((item) => item.estado === loc.estado) || null

  const recentes = Array.isArray(monitoramento.registros_recentes)
    ? monitoramento.registros_recentes
    : []

  const focosMunicipio = recentes.filter(
    (r) => r.estado === loc.estado && r.municipio,
  )

  const pontosOficiaisProximos = focosMunicipio
    .filter((r) => r.latitude !== null && r.longitude !== null)
    .map((r) => ({
      id: `oficial-${r.id}`,
      codigo: `INPE (${r.valor} ${r.unidade})`,
      tipo: r.tipo_metrica === 'foco_de_calor' ? 'queimada' : 'desmatamento',
      municipio: r.municipio,
      estado: r.estado,
      latitude: r.latitude,
      longitude: r.longitude,
    }))

  return {
    localizacao: loc,
    poligonoArea,
    ufResumo,
    focosMunicipio,
    pontosOficiaisProximos,
  }
}
